document
    .querySelectorAll(
        ".filter-button"
    )
    .forEach(button => {


        button.addEventListener(
            "click",
            () => {


                // フィルター変更
                currentFilter =
                    button.dataset.filter;


                // 全ボタンのactiveを外す
                document
                    .querySelectorAll(
                        ".filter-button"
                    )
                    .forEach(
                        b =>
                            b.classList
                                .remove(
                                    "active"
                                )
                    );


                // 押したボタンをactive
                button.classList.add(
                    "active"
                );


                // 再表示
                displayCards();

            }
        );

    });

